import Foundation
import NotchShell
import Observation

struct ClipboardItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable {
        case text, image, files
    }

    let id: UUID
    let kind: Kind
    var text: String?
    /// File name of the PNG inside the clipboard images directory.
    var imageFile: String?
    var filePaths: [String]?
    var sourceAppName: String?
    var date: Date
    var isPinned = false

    /// Identity used to collapse duplicates (copying the same text twice).
    var contentKey: String {
        switch kind {
        case .text: "t:" + (text ?? "")
        case .files: "f:" + (filePaths ?? []).joined(separator: "\n")
        case .image: "i:" + id.uuidString
        }
    }

    var previewText: String {
        switch kind {
        case .text: (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .files: (filePaths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        case .image: "Image"
        }
    }
}

/// Decides whether a pasteboard change should be recorded.
enum ClipboardFilter {
    /// Markers apps use to say "don't store this" (nspasteboard.org conventions).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        internalType,
    ]

    /// Added to everything NotchPilot itself writes, so re-copying an item isn't recorded twice.
    static let internalType = "com.notchpilot.app.clipboard-internal"

    static func shouldRecord(types: [String], sourceBundleID: String?, excludedBundleIDs: Set<String>) -> Bool {
        if types.contains(where: ignoredTypes.contains) { return false }
        if let sourceBundleID, excludedBundleIDs.contains(sourceBundleID) { return false }
        return true
    }
}

/// Clipboard history persisted to `clipboard.json`, images stored as PNG files.
@MainActor
@Observable
final class ClipboardStore {
    private(set) var items: [ClipboardItem] = []
    var maxItems: Int {
        didSet {
            defaults.set(maxItems, forKey: "clipboard.maxItems")
            trim()
            save()
        }
    }

    @ObservationIgnored private let file: JSONFile<[ClipboardItem]>
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored let imagesDirectory: URL

    init(directory: URL = AppPaths.supportDirectory, defaults: UserDefaults = .standard) {
        self.defaults = defaults
        file = JSONFile(url: directory.appendingPathComponent("clipboard.json"))
        imagesDirectory = directory.appendingPathComponent("clipboard-images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
        defaults.register(defaults: ["clipboard.maxItems": 200])
        maxItems = defaults.integer(forKey: "clipboard.maxItems")
        items = file.load() ?? []
    }

    func add(_ item: ClipboardItem) {
        if let existing = items.firstIndex(where: { $0.contentKey == item.contentKey }) {
            // Same content copied again: move it to the top, keep its pin.
            var moved = items.remove(at: existing)
            moved.date = item.date
            moved.sourceAppName = item.sourceAppName
            items.insert(moved, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        save()
    }

    func imageURL(for item: ClipboardItem) -> URL? {
        item.imageFile.map { imagesDirectory.appendingPathComponent($0) }
    }

    func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].isPinned.toggle()
        save()
    }

    func remove(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        deleteFiles(of: items.remove(at: i))
        save()
    }

    /// Removes everything except pinned items.
    func clearUnpinned() {
        items.filter { !$0.isPinned }.forEach(deleteFiles)
        items.removeAll { !$0.isPinned }
        save()
    }

    func search(_ query: String) -> [ClipboardItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let matches = q.isEmpty ? items : items.filter { $0.previewText.localizedCaseInsensitiveContains(q) }
        // Pinned first, then most recent.
        return matches.filter(\.isPinned) + matches.filter { !$0.isPinned }
    }

    /// Evicts the oldest unpinned items beyond `maxItems`.
    private func trim() {
        var unpinnedSeen = 0
        var kept: [ClipboardItem] = []
        for item in items {
            if item.isPinned {
                kept.append(item)
            } else if unpinnedSeen < maxItems {
                unpinnedSeen += 1
                kept.append(item)
            } else {
                deleteFiles(of: item)
            }
        }
        items = kept
    }

    private func deleteFiles(of item: ClipboardItem) {
        if let url = imageURL(for: item) { try? FileManager.default.removeItem(at: url) }
    }

    private func save() {
        file.save(items)
    }
}
